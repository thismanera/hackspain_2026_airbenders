/**
 * One-shot generator for lib/features/portfolio/companies.seed.ts.
 *
 * Picks a representative slice of dataset/companies.csv — a few multi-company
 * groups so the group aval/contagio story has something to stand on, plus
 * standalone companies — and writes their real anonymised metadata out as a
 * committed TypeScript literal. Re-run only if the slice needs to change.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const COUNTRY_ALIASES = {
  ESPAÑA: "ES",
  España: "ES",
  Espanya: "ES",
  ESPANYA: "ES",
  Spain: "ES",
  Alemania: "DE",
  Italia: "IT",
  Portugal: "PT",
  Malaysia: "MY",
};

function normalizeCountry(raw) {
  const trimmed = (raw ?? "").trim();
  return COUNTRY_ALIASES[trimmed] ?? trimmed;
}

const lines = readFileSync("dataset/companies.csv", "utf8").trim().split(/\r?\n/);
const rows = lines.slice(1).map((line) => {
  const [id, groupId, country, currency, erp] = line.split(",");
  return { id, groupId, country, currency, erp };
});

const byGroup = new Map();
for (const row of rows) {
  const bucket = byGroup.get(row.groupId) ?? [];
  bucket.push(row);
  byGroup.set(row.groupId, bucket);
}

const groups = [...byGroup.entries()].sort((a, b) => a[0].localeCompare(b[0]));
const ofSize = (size, count) => groups.filter(([, members]) => members.length === size).slice(0, count);

const chosen = [...ofSize(6, 2), ...ofSize(4, 2), ...ofSize(3, 2), ...ofSize(2, 2), ...ofSize(1, 14)];
const selected = chosen.flatMap(([, members]) => members);

const body = selected
  .map(
    (row) =>
      `  { id: "${row.id}", groupId: "${row.groupId}", country: "${normalizeCountry(row.country)}", currency: "${row.currency}", erp: "${row.erp ?? ""}" },`,
  )
  .join("\n");

const file = `// Generated by scripts/gen-company-seed.mjs from dataset/companies.csv.
// Real anonymised metadata for a representative slice of the portfolio. Only the
// scores built on top of it in fixtures.ts are synthetic.

export type CompanySeed = {
  id: string;
  groupId: string;
  country: string;
  currency: string;
  erp: string;
};

export const COMPANY_SEED: CompanySeed[] = [
${body}
];
`;

mkdirSync("lib/features/portfolio", { recursive: true });
writeFileSync("lib/features/portfolio/companies.seed.ts", file);
console.log(`Wrote ${selected.length} companies across ${chosen.length} groups.`);
